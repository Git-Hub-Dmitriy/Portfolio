export default function timeTo12Pm(time: number) {
  switch (time) {
    case 15: {
      return 3;
    }
    case 16: {
      return 4;
    }
    case 17: {
      return 5;
    }
    case 18: {
      return 6;
    }
    case 19: {
      return 7;
    }
    case 20: {
      return 8;
    }
    case 21: {
      return 9;
    }
    case 22: {
      return 10;
    }
  }
}
